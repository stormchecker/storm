#pragma once

#include <cstdint>

namespace storm::counterexamples {

/*!
 * The default values of the options that configure counterexample generation. Both the generators and the
 * command-line settings take their defaults from here.
 */
struct CounterexampleOptions {
    /// Whether reachability of a target state is encoded in the MaxSAT-based generation.
    bool encodeReachability = false;

    /// Whether dynamic constraints are generated in the MaxSAT-based generation.
    bool useDynamicConstraints = true;

    /// Whether the scheduler cuts are added in the MILP-based generation.
    bool useSchedulerCuts = false;

    /// The maximal number of paths generated by the shortest-path-based generation.
    uint64_t shortestPathMaxK = 10;
};

}  // namespace storm::counterexamples
